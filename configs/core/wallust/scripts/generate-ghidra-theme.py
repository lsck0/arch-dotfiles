#!/usr/bin/env python3
"""Write ~/.cache/wal/colors-ghidra.theme, a Flat Dark theme recoloured from the wallpaper palette."""

import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.realpath(__file__)), "lib"))

from palette import (  # noqa: E402
    dim_toward,
    lift,
    mix,
    readable_on,
    rgb_to_hex,
    selection_pair,
    semantic,
    tone_map,
    vivify,
    wal_load,
    write_atomic,
)

# ghidra reads it on start only, through the Theme=File:... preference configs/pentesting/ghidra/link.sh sets
OUT = os.path.expanduser("~/.cache/wal/colors-ghidra.theme")


def main():
    slot = wal_load("generate-ghidra-theme")
    if slot is None:
        return 1

    bg = tone_map(slot("background", "#0b1019"))
    fg = readable_on(bg, slot("foreground", "#c2c3c5"), 7.0)
    dim = dim_toward(fg, bg, 3.0)
    # comments and bytes recede but stay body-text readable
    muted = readable_on(bg, dim_toward(fg, bg, 4.5))
    accent = vivify(slot("color4", "#B68B74"), 0.45, 0.55)
    selection, on_selection = selection_pair(accent, fg)

    def on(name, fallback):
        # wal slots can sit close to bg; listing and decompiler text must stay readable
        return readable_on(bg, vivify(slot(name, fallback), 0.30, 0.55))

    keyword = readable_on(bg, accent)
    name = on("color6", "#A76495")
    constant = on("color2", "#8BA87A")
    variable = on("color3", "#C9A86A")
    param = on("color5", "#A76495")
    special = on("color1", "#C06C6C")
    error = semantic("error", accent, bg)
    warn = semantic("warn", accent, bg)

    colors = [
        # the flat dark laf derives every panel, table and text colour from these system ids; its panel
        # background shares a value with the frame border, so bg.border is the window surface
        ("[color]system.color.bg.view", bg),
        ("[color]system.color.bg.border", lift(bg, 0.04)),
        ("[color]system.color.bg.control", lift(bg, 0.08)),
        ("[color]system.color.bg.tooltip", lift(bg, 0.08)),
        ("[color]system.color.bg.selected.view", selection),
        ("[color]system.color.fg.view", fg),
        ("[color]system.color.fg.control", fg),
        ("[color]system.color.fg.tooltip", fg),
        ("[color]system.color.fg.selected.view", on_selection),
        ("[color]system.color.fg.disabled", dim),
        # flat dark's menu bar grey matches no system id
        ("[laf.color]MenuBar.background", lift(bg, 0.04)),

        ("color.bg.table.row.alt", lift(bg, 0.025)),
        ("color.bg.currentline", mix(bg, accent, 0.16)),
        ("color.bg.selection", mix(bg, accent, 0.32)),
        ("color.bg.highlight", mix(bg, warn, 0.28)),
        ("color.cursor.focused", accent),
        ("color.cursor.unfocused", dim),
        ("color.fg.error", error),

        # listing; the rest keeps flat dark's tuned dark defaults
        ("color.fg.listing.bytes", muted),
        ("color.fg.listing.mnemonic", keyword),
        ("color.fg.listing.mnemonic.unimplemented", keyword),
        ("color.fg.listing.register", variable),
        ("color.fg.listing.constant", constant),
        ("color.fg.listing.label.primary", name),
        ("color.fg.listing.label.local", constant),
        ("color.fg.listing.function.name", name),
        ("color.fg.listing.function.variable", param),
        ("color.fg.listing.function.variable.assigned", param),
        ("color.fg.listing.ext.entrypoint", special),
        ("color.fg.listing.xref", constant),
        ("color.fg.listing.xref.read", name),
        ("color.fg.listing.xref.write", warn),
        ("color.fg.listing.comment.eol", muted),
        ("color.fg.listing.comment.pre", muted),
        ("color.fg.listing.comment.post", muted),
        ("color.fg.listing.comment.plate", muted),
        ("color.fg.listing.comment.auto", muted),

        ("color.fg.decompiler.keyword", keyword),
        ("color.fg.decompiler.type", name),
        ("color.fg.decompiler.constant", constant),
        ("color.fg.decompiler.variable", variable),
        ("color.fg.decompiler.parameter", param),
        ("color.fg.decompiler.global", special),
        ("color.fg.decompiler.external.function", special),
        ("color.fg.decompiler.comment", muted),
        ("color.fg.decompiler.error", error),
        ("color.fg.decompiler.special", error),
    ]

    lines = [
        "// generated by configs/core/wallust/scripts/generate-ghidra-theme.py on every wallpaper switch, do not edit",
        "name = Wallust",
        "lookAndFeel = Flat Dark",
        "useDarkDefaults = true",
        "",
    ]
    lines += ["%s = %s" % (key, rgb_to_hex(rgb, "#")) for key, rgb in colors]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    write_atomic(OUT, "\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
